"""P5 import comparator contract; synthetic echoes are NOT TV parity evidence."""
import csv
import hashlib
import io
from dataclasses import replace
from datetime import datetime, timedelta, timezone

import pytest

from core.data.contracts import Bar, DataZone, MarketDataSet
from research.pine_import.p5_reference_compare import (
    PineReferenceError,
    compare_pine_reference,
    export_expected_columns_for_fixture,
    source_pin_for,
)


def _market():
    bars = []
    for i in range(98):
        val = (99 + i * 0.55) if i < 53 else (128.15 - (i - 53) * 0.85)
        bars.append(Bar(
            datetime(2020, 1, 1, tzinfo=timezone.utc) + timedelta(days=i),
            "QQQ", val, val + 1.2, val - 1.2, val, 5000.0,
        ))
    return MarketDataSet("p5-reference-input", DataZone.DEVELOPMENT, tuple(bars))


def _manifest_and_csv(dataset, name):
    # In these tests the reference is deliberately generated by our own
    # adapter to verify schema/guardrails, NOT from TradingView.
    data = export_expected_columns_for_fixture(dataset, name)
    out = io.StringIO()
    writer = csv.DictWriter(out, fieldnames=list(data[0]))
    writer.writeheader()
    writer.writerows(data)
    payload = out.getvalue().encode("utf-8")
    manifest = {
        "indicator": name,
        "original_upload_sha256": source_pin_for(name),
        "dataset_hash": dataset.dataset_hash,
        "reference_csv_sha256": hashlib.sha256(payload).hexdigest(),
        "claimed_export_origin": "UNVERIFIED synthetic test fixture",
    }
    return manifest, payload


@pytest.mark.parametrize("indicator", ["boswaves", "shaakuni"])
def test_reference_echo_is_numeric_match_only_never_approval(indicator):
    market = _market()
    manifest, csv_data = _manifest_and_csv(market, indicator)
    check = compare_pine_reference(market, manifest, csv_data)
    assert check.status == "NUMERIC_MATCH_ONLY_UNAUTHENTICATED"
    assert check.mismatch_count == 0
    assert check.compared_rows == 98
    assert check.source_archive_sha256 == source_pin_for(indicator)
    assert check.independent_tradingview_origin_authenticated is False
    assert check.full_pine_parity_approved is False
    assert check.operational_feature_promotion_allowed is False


def test_single_changed_numeric_and_event_values_are_detected():
    market = _market()
    manifest, csv_data = _manifest_and_csv(market, "boswaves")
    rows = list(csv.DictReader(io.StringIO(csv_data.decode())))
    rows[70]["alma"] = "800000"
    rows[80]["trend"] = "3"
    out = io.StringIO()
    writer = csv.DictWriter(out, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)
    corrupt = out.getvalue().encode()
    manifest["reference_csv_sha256"] = hashlib.sha256(corrupt).hexdigest()
    comparison = compare_pine_reference(market, manifest, corrupt)
    assert comparison.status == "MISMATCH"
    assert comparison.mismatch_count == 2
    assert {x.field for x in comparison.first_mismatches} == {"alma", "trend"}
    assert comparison.full_pine_parity_approved is False


def test_source_dataset_or_csv_hash_mismatch_is_rejected():
    market = _market()
    manifest, content = _manifest_and_csv(market, "shaakuni")
    with pytest.raises(PineReferenceError):
        compare_pine_reference(market, {**manifest, "original_upload_sha256": "0"*64}, content)
    with pytest.raises(PineReferenceError):
        compare_pine_reference(market, {**manifest, "dataset_hash": "bad"}, content)
    with pytest.raises(PineReferenceError):
        compare_pine_reference(market, manifest, content + b"x")


def test_shifted_or_duplicate_timestamps_are_rejected():
    market = _market()
    manifest, csv_data = _manifest_and_csv(market, "boswaves")
    rows = list(csv.DictReader(io.StringIO(csv_data.decode())))
    rows[1]["timestamp"] = rows[0]["timestamp"]
    out = io.StringIO()
